from fastapi import APIRouter, UploadFile, File, Form, HTTPException
from typing import Optional, Dict, Any
import hashlib

from ..models import CertificateVerificationResponse, VerifyHashRequest
from ..pdf_generator.hasher import compute_sha256_bytes
from .. import database as db

router = APIRouter(prefix="/verify", tags=["Verification"])

@router.post("/hash", response_model=CertificateVerificationResponse)
def verify_by_hash(req: VerifyHashRequest):
    """Verifies a certificate by its SHA-256 cryptographic digest"""
    sha_hash = req.sha256_hash.strip().lower()
    
    cert_record = db.find_certificate_by_hash(sha_hash)
    if cert_record:
        return CertificateVerificationResponse(
            is_valid=True,
            status="VERIFIED",
            message="Certificate is authentic and unaltered. Cryptographic SHA-256 hash matches the state registry record.",
            case_id=cert_record["case_id"],
            mlc_number=cert_record.get("mlc_number"),
            patient_name=cert_record.get("patient_name"),
            doctor_name=cert_record.get("doctor_name"),
            sha256_hash=cert_record["sha256_hash"],
            generated_at=cert_record.get("generated_at"),
            injuries_count=cert_record.get("injuries_count"),
            legal_opinion=cert_record.get("legal_opinion")
        )
    else:
        return CertificateVerificationResponse(
            is_valid=False,
            status="TAMPERED",
            message="Hash verification failed. No valid certificate record matches this cryptographic digest.",
            sha256_hash=sha_hash
        )

@router.post("/upload", response_model=CertificateVerificationResponse)
async def verify_uploaded_pdf(file: UploadFile = File(...)):
    """Verifies an uploaded PDF certificate by computing its SHA-256 hash on the fly"""
    content = await file.read()
    if not content:
        raise HTTPException(status_code=400, detail="Uploaded file is empty.")

    uploaded_hash = compute_sha256_bytes(content)
    
    cert_record = db.find_certificate_by_hash(uploaded_hash)
    if cert_record:
        return CertificateVerificationResponse(
            is_valid=True,
            status="VERIFIED",
            message="Document verified! SHA-256 integrity check passed. The uploaded PDF is authentic and exactly matches the original issued record.",
            case_id=cert_record["case_id"],
            mlc_number=cert_record.get("mlc_number"),
            patient_name=cert_record.get("patient_name"),
            doctor_name=cert_record.get("doctor_name"),
            sha256_hash=uploaded_hash,
            generated_at=cert_record.get("generated_at"),
            injuries_count=cert_record.get("injuries_count"),
            legal_opinion=cert_record.get("legal_opinion")
        )
    else:
        return CertificateVerificationResponse(
            is_valid=False,
            status="TAMPERED",
            message="Integrity check failed: This document has been modified, tampered with, or was not generated by MLC Assist registry.",
            sha256_hash=uploaded_hash
        )
